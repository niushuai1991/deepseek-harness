#!/usr/bin/env node
// Regenerates apps/desktop/deploy-root/package.json: the dependency-only
// deploy root of the desktop sidecar closure.
//
// Inside a pnpm deploy with injected workspace packages, one injected entry
// does not link its workspace-specifier dependencies and peers, so every
// workspace package any booted package imports must be a DIRECT dependency of
// the deploy root (resolvable by walking up to its top-level node_modules).
// This script computes that set: the transitive closure over workspace
// dependency and peer edges, seeded from the dsh CLI's dependencies and
// devDependencies (the devDependencies supply the bundles' runtime peers at
// the repository root) plus the vendored framework packages.
//
// Run after adding packages to the booted profiles, then `pnpm install`.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const root = resolve(appDir, '../..')
const target = join(appDir, 'deploy-root', 'package.json')

/** Every workspace package manifest, keyed by package name. */
function loadWorkspace() {
  const manifests = new Map()
  const groups = [
    join(root, 'packages'),
    join(root, 'vendor'),
    join(root, 'apps'),
  ]
  const visit = (directory, depth) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name === 'node_modules' || entry.name.startsWith('.')) continue
      const path = join(directory, entry.name, 'package.json')
      let manifest
      try {
        manifest = JSON.parse(readFileSync(path, 'utf8'))
      } catch {
        if (depth === 0) visit(join(directory, entry.name), 1)
        continue
      }
      manifests.set(manifest.name, manifest)
    }
  }
  for (const group of groups) visit(group, 0)
  for (const nested of ['native/landlock-run', 'native/landlock-run/packages', 'apps/desktop/deploy-root']) {
    try {
      const manifest = JSON.parse(readFileSync(join(root, nested, 'package.json'), 'utf8'))
      manifests.set(manifest.name, manifest)
    } catch {
      // Not all optional roots exist in every checkout variant.
    }
  }
  return manifests
}

const workspace = loadWorkspace()
const isWorkspaceRef = (spec) => spec === 'workspace:' || spec.startsWith('workspace:')

/** Union of workspace-specifier dependency and peer names of one package. */
function workspaceEdges(manifest) {
  const names = new Set()
  for (const field of ['dependencies', 'peerDependencies', 'devDependencies']) {
    for (const [name, spec] of Object.entries(manifest[field] ?? {})) {
      if (isWorkspaceRef(spec) && workspace.has(name) && name !== '@deepseek-ai/dsh-desktop-deploy') names.add(name)
    }
  }
  return names
}

// Seed: the dsh CLI's whole workspace face (dependencies plus the devDeps
// that supply runtime peers at the repository root), the vendored framework
// trio every harness package peers on, and the CLI itself.
const cli = workspace.get('@deepseek-ai/dsh')
if (cli === undefined) throw new Error('generate-deploy-root: @deepseek-ai/dsh not found in the workspace')
const closure = new Set(['@deepseek-ai/dsh', '@deepseek-ai/cordis-plugin-group', '@deepseek-ai/cosmokit', '@deepseek-ai/schemastery'])
for (const name of workspaceEdges(cli)) closure.add(name)

// Fixpoint over workspace dependency and peer edges.
for (let added = true; added;) {
  added = false
  for (const name of [...closure]) {
    const manifest = workspace.get(name)
    if (manifest === undefined) throw new Error(`generate-deploy-root: ${name} missing from the workspace`)
    for (const edge of workspaceEdges(manifest)) {
      if (!closure.has(edge)) {
        closure.add(edge)
        added = true
      }
    }
  }
}

// Registry dependencies stay as the CLI declares them.
const registry = Object.fromEntries(
  Object.entries(cli.dependencies ?? {}).filter(([, spec]) => !isWorkspaceRef(spec)),
)

const dependencies = {}
for (const name of [...closure].sort()) dependencies[name] = 'workspace:^'
for (const [name, spec] of Object.entries(registry).sort(([a], [b]) => a.localeCompare(b))) dependencies[name] = spec

const manifest = {
  name: '@deepseek-ai/dsh-desktop-deploy',
  description: 'Dependency-only deploy root defining the desktop installer\'s sidecar closure; pnpm deploy materializes this manifest and node_modules. GENERATED by apps/desktop/scripts/generate-deploy-root.mjs — rerun it after changing the booted profiles, then pnpm install.',
  version: cli.version,
  private: true,
  type: 'module',
  dependencies,
}
writeFileSync(target, `${JSON.stringify(manifest, null, 2)}\n`)
console.log(`generate-deploy-root: ${String(closure.size)} workspace dependencies + ${String(Object.keys(registry).length)} registry dependencies -> ${target}`)
